#!/usr/bin/env python3
"""Generate the shared 2.3.2 explosive geometry for modern and classic clients."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
VERSIONS = ("1.20.1", "1.20.2", "1.21.1", "26.1.2", "26.2")
LOADERS = ("forge", "fabric", "neoforge")
FACES = ("down", "up", "north", "south", "west", "east")
# Opaque, small pixel-art material swatches; original inventory sprites stay intact.
COLORS = ((170, 38, 29), (226, 201, 146), (70, 62, 47), (240, 125, 30),
          (70, 84, 34), (103, 117, 49), (143, 147, 126), (47, 52, 37))


def uv(material: int) -> list[float]:
    x, y = (material % 4) * 4, (material // 4) * 4
    return [x + 0.25, y + 0.25, x + 3.75, y + 3.75]


def cube(start: list[float], end: list[float], material: int) -> dict:
    return {"from": start, "to": end,
            "faces": {face: {"texture": "#material", "uv": uv(material)} for face in FACES}}


def geometry(name: str) -> list[dict]:
    if name == "dynamite":
        parts = [cube([4, 2, 5], [7.5, 12, 8.5], 0),
                 cube([8, 2, 5], [11.5, 12, 8.5], 0),
                 cube([6, 2, 9], [9.5, 12, 12.5], 0)]
        for y in (4, 9):
            parts.extend([cube([3.8, y, 4.8], [11.7, y + 1, 5.1], 1),
                          cube([3.8, y, 12.4], [11.7, y + 1, 12.7], 1),
                          cube([3.8, y, 5.1], [4.1, y + 1, 12.4], 1),
                          cube([11.4, y, 5.1], [11.7, y + 1, 12.4], 1)])
        parts.extend([cube([7.1, 12, 9.9], [7.9, 14, 10.7], 2),
                      cube([7.1, 13.2, 9.9], [9.4, 14, 10.7], 2),
                      cube([9.1, 13.1, 9.8], [10, 14.1, 10.8], 3)])
        return parts
    # A faceted olive body with raised segmented tiles, neck, spoon and pin ring.
    parts = [cube([5, 2, 5], [11, 3.5, 11], 4),
             cube([4, 3.5, 4], [12, 9.5, 12], 4),
             cube([5, 9.5, 5], [11, 11, 11], 4)]
    for y in (3.8, 6.7):
        for x in (4.2, 8.2):
            parts.extend([cube([x, y, 3.7], [x + 3.6, y + 2.5, 4.15], 5),
                          cube([x, y, 11.85], [x + 3.6, y + 2.5, 12.3], 5)])
        for z in (4.2, 8.2):
            parts.extend([cube([3.7, y, z], [4.15, y + 2.5, z + 3.6], 5),
                          cube([11.85, y, z], [12.3, y + 2.5, z + 3.6], 5)])
    parts.extend([cube([6.5, 11, 6.5], [9.5, 12.5, 9.5], 7),
                  cube([6.5, 12.5, 6.5], [11.5, 13.3, 9.5], 6),
                  cube([11, 6.5, 7], [12, 12.5, 9], 6),
                  cube([4.5, 11.8, 7.5], [6.5, 12.4, 8.1], 6),
                  cube([3.9, 10.8, 7.5], [4.5, 12.4, 8.1], 6),
                  cube([4.5, 10.8, 7.5], [6.5, 11.4, 8.1], 6)])
    return parts


def model(name: str) -> dict:
    return {
        "credit": "Useful Tools 2.3.2 shared explosive geometry",
        "ambientocclusion": False,
        "gui_light": "front",
        "textures": {"particle": f"usefultoolsmod:item/{name}",
                     "material": "usefultoolsmod:item/explosive_materials"},
        "elements": geometry(name),
        "display": {
            "gui": {"rotation": [25, 225, 0], "scale": [0.85] * 3},
            "ground": {"rotation": [0, 30, 0], "translation": [0, 2, 0], "scale": [0.7] * 3},
            "fixed": {"rotation": [0, 180, 0], "scale": [0.75] * 3},
            "head": {"translation": [0, 13, 7], "scale": [0.7] * 3},
            "thirdperson_righthand": {"rotation": [0, 0, 0], "translation": [0, 2, 1], "scale": [0.65] * 3},
            "thirdperson_lefthand": {"rotation": [0, 0, 0], "translation": [0, 2, 1], "scale": [0.65] * 3},
            "firstperson_righthand": {"rotation": [0, -25, 15], "translation": [-1, 6, -1], "scale": [0.5] * 3},
            "firstperson_lefthand": {"rotation": [0, 25, -15], "translation": [-1, 6, -1], "scale": [0.5] * 3},
        },
    }


def texture() -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    rows = bytearray()
    for y in range(16):
        rows.append(0)
        for x in range(16):
            color = COLORS[((y // 4) * 4 + x // 4) % len(COLORS)]
            shade = (-7, 0, 4, 0)[(x + y * 3) % 4]
            rows.extend((*[max(0, min(255, c + shade)) for c in color], 255))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 16, 16, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b""))


def classic_geometry() -> bytes:
    result = ['package com.stonytark.usefultoolsmod.classic.client;', '',
              '/** Generated by scripts/sync-2.3.2-explosive-models.py. Same cuboids as modern JSON. */',
              'final class ExplosiveGeometry {', '    private ExplosiveGeometry() {}']
    for name in ("dynamite", "grenade"):
        result.append(f'    static final float[][] {name.upper()} = {{')
        for part in geometry(name):
            values = part['from'] + part['to'] + part['faces']['up']['uv']
            result.append('        {' + ', '.join(f'{v:g}F' for v in values) + '},')
        result.append('    };')
    result.append('}')
    return ('\n'.join(result) + '\n').encode()


def outputs() -> dict[Path, bytes]:
    result = {}
    atlas = texture()
    for version in VERSIONS:
        for loader in LOADERS:
            assets = ROOT / version / loader / 'src/main/resources/assets/usefultoolsmod'
            result[assets / 'textures/item/explosive_materials.png'] = atlas
            for name in ('dynamite', 'grenade'):
                result[assets / f'models/item/{name}.json'] = (json.dumps(model(name), indent=2) + '\n').encode()
    result[ROOT / '1.7.10/src/main/resources/assets/usefultoolsmod/textures/items/explosive_materials.png'] = atlas
    result[ROOT / '1.7.10/src/main/java/com/stonytark/usefultoolsmod/classic/client/ExplosiveGeometry.java'] = classic_geometry()
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify without writing')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        print('\n'.join(stale))
        return 1
    print('Explosive models: all 16 targets current' if args.check else 'Generated explosive models for all 16 targets')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
